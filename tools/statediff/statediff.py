BUTTONS = {"A": 0x8000, "B": 0x4000, "Z": 0x2000, "START": 0x1000, "DUP": 0x0800, "DDOWN": 0x0400,
           "DLEFT": 0x0200, "DRIGHT": 0x0100, "L": 0x0020, "R": 0x0010, "CUP": 0x0008, "CDOWN": 0x0004,
           "CLEFT": 0x0002, "CRIGHT": 0x0001}


def write_tour_header(entrances=(), frames=0):
    """build/statediff/tour_script.h for statediff_input.h (empty = no scene tour)."""
    ents = ", ".join("0x%03X" % e for e in entrances) or "-1"
    text = ("/* generated by tools/statediff - scene tour entrances */\n#define STATEDIFF_TOUR_LEN %d\n"
            "#define STATEDIFF_TOUR_FRAMES %d\nstatic s32 sStateDiffTour[] = { %s };\n" % (len(entrances), frames, ents))
    path = os.path.join(OUT, "tour_script.h")
    os.makedirs(OUT, exist_ok=True)
    if not os.path.exists(path) or open(path).read() != text:
        open(path, "w").write(text)
    return path


def write_script_header(name):
    """tools/statediff/scripts/<name>.txt -> build/statediff/input_script_<name>.h (C table for statediff_input.h)."""
    rows = []
    for line in open(os.path.join(HERE, "scripts", name + ".txt")):
        line = line.split("#")[0].strip()
        if not line:
            continue
        frame, btn, x, y = line.split()
        mask = 0
        for b in btn.split("|"):
            mask |= 0 if b == "0" else BUTTONS[b.upper()]
        rows.append("    { %d, 0x%04X, %d, %d }," % (int(frame), mask, int(x), int(y)))
    path = os.path.join(OUT, "input_script_%s.h" % name)
    os.makedirs(OUT, exist_ok=True)
    text = "/* generated by tools/statediff/statediff.py from scripts/%s.txt */\nstatic s32 sStateDiffScript[][4] = {\n%s\n};\n" % (name, "\n".join(rows))
    if not os.path.exists(path) or open(path).read() != text:
        open(path, "w").write(text)
    # the 3DS build includes "input_script.h" from build/statediff: keep that copy in sync
    cur = os.path.join(OUT, "input_script.h")
    if not os.path.exists(cur) or open(cur).read() != text:
        open(cur, "w").write(text)
    return path


