def read_regs(g, syms):
    """gRegEditor->data (RegEditor: 5 s32 then s16 data[29 * 96]), appended to the globals blob"""
    ptr = struct.unpack(">I", g.read_mem(syms["gRegEditor"], 4))[0]
    return g.read_mem(ptr + 0x14, REG_COUNT * 2)


